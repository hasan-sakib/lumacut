"""Lumacut document models, generated from packages/schema (the Zod source of truth).

`models.py` is generated by `make gen-schema`; never edit it by hand. Validate documents from
JSON (`parse_project_json`, `parse_op_json`): JSON arrays map to the tuple types (Vec2, Rgb), and
the strict scalar types match Zod exactly (no bool-as-number, no numeric strings). Optional fields
use Pydantic's MISSING sentinel, so "absent" and "null" stay distinct exactly as in Zod: an absent
field reads as `MISSING`, and an explicit `null` is rejected.
"""

from pydantic import TypeAdapter

from lumacut_schema import models
from lumacut_schema.models import Op, Project

CURRENT_SCHEMA_VERSION = 1

op_adapter: TypeAdapter[Op] = TypeAdapter(Op)


def parse_project_json(data: str | bytes) -> Project:
    """Validate a project document given as JSON text."""
    return Project.model_validate_json(data)


def parse_op_json(data: str | bytes) -> Op:
    """Validate a single op (or batch) given as JSON text."""
    return op_adapter.validate_json(data)


def dump_json(value: Project | Op) -> bytes:
    """Serialize back to JSON in the document's wire form (MISSING fields are omitted)."""
    if isinstance(value, Project):
        return value.model_dump_json(by_alias=True).encode()
    return op_adapter.dump_json(value, by_alias=True)


__all__ = [
    "CURRENT_SCHEMA_VERSION",
    "Op",
    "Project",
    "dump_json",
    "models",
    "op_adapter",
    "parse_op_json",
    "parse_project_json",
]
