#!/usr/bin/env bash
# Regenerates the JSON Schema and the Pydantic models from packages/schema (Zod).
# Usage: scripts/gen-schema.sh [json_out] [models_out]   (defaults: the committed files)
set -euo pipefail
unset VIRTUAL_ENV  # always use the repo .venv

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
JSON_OUT="${1:-$ROOT/packages/schema/generated/lumacut.schema.json}"
MODELS_OUT="${2:-$ROOT/packages/schema/py/lumacut_schema/models.py}"

(cd "$ROOT/packages/schema" && node scripts/gen-json-schema.ts "$JSON_OUT" >/dev/null)

# Generate inside the package dir so every formatter pass sees the repo's ruff config, whatever
# the final destination (the drift check writes to a temp dir).
WORK="$ROOT/packages/schema/py/lumacut_schema/.models.gen.py"
trap 'rm -f "$WORK"' EXIT

uv run --project "$ROOT" datamodel-codegen \
  --input "$JSON_OUT" \
  --input-file-type jsonschema \
  --output "$WORK" \
  --output-model-type pydantic_v2.BaseModel \
  --target-python-version 3.12 \
  --use-annotated \
  --field-constraints \
  --use-standard-collections \
  --use-union-operator \
  --enum-field-as-literal all \
  --extra-fields forbid \
  --disable-timestamp \
  --use-title-as-name \
  --use-type-alias \
  --use-schema-description \
  --strict-types str int float bool \
  --use-missing-sentinel \
  --target-pydantic-version 2.14 \
  --formatters ruff-format \
  --custom-file-header "# GENERATED by \`make gen-schema\` from packages/schema (Zod). Do not edit by hand."

uv run --project "$ROOT" ruff check --quiet --fix --exit-zero --config "$ROOT/pyproject.toml" "$WORK"
uv run --project "$ROOT" ruff format --quiet --config "$ROOT/pyproject.toml" "$WORK"
mv "$WORK" "$MODELS_OUT"
echo "generated: $JSON_OUT"
echo "generated: $MODELS_OUT"
